/**
 * Guide content — one document per /guide page.
 *
 * Shape rules (they are what make these pages quotable by an answer engine):
 *   - `answer` is 40–60 words and self-contained: read alone, it still answers
 *     the page's question. It is also the page's meta description source of
 *     truth in spirit, and the FIRST paragraph on the page.
 *   - every `section` is one H2 and 120–180 words of prose that does not
 *     depend on the section before it.
 *   - `faq` feeds BOTH the visible <details> list and FAQPage JSON-LD, like
 *     `faq.ts` does for the marketing pages.
 *   - `related` is the internal-link block (five or more links per page).
 *
 * Every product fact here must be true of the shipped web editor: modes,
 * accepted files, output size, per-plan limits. Nothing is measured or
 * benchmarked — numbers that need measuring live in `owner-numbers.ts` and
 * render as nothing until the owner fills them in.
 */
