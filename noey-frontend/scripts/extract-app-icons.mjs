#!/usr/bin/env node
/**
 * Copies the Lucide icons the real editor (web/src) uses into the site, so the
 * editor mock-ups draw the same glyphs. Reads web/node_modules (read-only) and
 * writes src/components/mockups/app/icons.ts.
 *
 *   node scripts/extract-app-icons.mjs [--web ../web]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const args = process.argv.slice(2);
const webAt = args.indexOf("--web");
const WEB = resolve(webAt === -1 ? join(import.meta.dirname, "..", "..", "web") : args[webAt + 1]);
const ICONS = join(WEB, "node_modules/lucide-react/dist/esm/icons");
const ALIASES = {
  AlertTriangle: "triangle-alert",
  HelpCircle: "circle-help",
  Loader2: "loader-circle",
  MoreHorizontal: "ellipsis",
};
const NAMES = [
  "AlertTriangle", "ArrowLeft", "ArrowLeftRight", "ArrowRight", "Check", "ChevronDown", "ChevronLeft", "ChevronRight", "Clapperboard", "Clock",
  "Copy", "Crosshair", "Download", "Eye", "EyeOff", "Film", "FolderOpen", "Gauge", "GripVertical", "HelpCircle", "Hourglass",
  "Layers", "Loader2", "Lock", "Magnet", "Maximize2", "Menu", "Mic", "MoreHorizontal", "Music2", "Pause", "Pencil", "Play", "Plus",
  "Redo2", "RefreshCw", "Repeat", "Repeat2", "Save", "Scan", "Scissors", "Settings", "Shapes", "Shuffle", "SkipBack", "SkipForward",
  "Smartphone", "Sparkles", "Square", "SquarePlay", "Trash2", "Undo2", "Upload", "UserRoundPen", "Volume2", "VolumeX", "X",
];
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])([0-9])/g, "$1-$2").toLowerCase();

const out = {};
for (const name of NAMES) {
  let file = join(ICONS, `${ALIASES[name] ?? kebab(name)}.mjs`);
  // Some names are re-exports of another icon file ("export { default } from './x.mjs'").
  const reexport = readFileSync(file, "utf8").match(/export \{ default \} from '\.\/([^']+)'/);
  if (reexport) file = join(ICONS, reexport[1]);
  const { __iconData } = await import(file);
  if (!__iconData) throw new Error(`no icon data in ${file}`);
  out[name] = __iconData.node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    void key;
    return [tag, rest];
  });
}

const license = readFileSync(join(WEB, "node_modules/lucide-react/LICENSE"), "utf8").split("\n").slice(0, 16).join("\n * ");
const body = `// Generated by scripts/extract-app-icons.mjs from the editor's own icon set
// (lucide-react, as used in web/src). Do not edit by hand.
/*
 * ${license}
 */

export type IconNode = ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>;

export const APP_ICONS = {
${Object.entries(out)
  .map(([name, node]) => `  ${name}: ${JSON.stringify(node)},`)
  .join("\n")}
} as const satisfies Record<string, IconNode>;

export type AppIconName = keyof typeof APP_ICONS;
`;
writeFileSync(join(import.meta.dirname, "../src/components/mockups/app/icons.ts"), body);
console.log(`${Object.keys(out).length} icons written`);
